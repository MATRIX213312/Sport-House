export const formatPrice = (priceInRub, lang) => {
  if (lang === 'en') {
    // 1 USD approx 95 RUB
    const usd = Math.round(priceInRub / 95);
    return `$${usd.toLocaleString('en-US')}`;
  }
  if (lang === 'uz') {
    // 1 RUB approx 140 UZS
    const uzs = Math.round(priceInRub * 140);
    return `${uzs.toLocaleString('ru-RU')} soʻm`;
  }
  if (lang === 'kz') {
    // 1 RUB approx 5.2 KZT
    const kzt = Math.round(priceInRub * 5.2);
    return `${kzt.toLocaleString('ru-RU')} ₸`;
  }
  return `${priceInRub.toLocaleString('ru-RU')} ₽`;
};
